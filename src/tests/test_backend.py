def run(state: ui.UIState, text: str) -> list[dict]:
    """One turn with the real backend behind it."""

    return pipeline.run_events(state, text, api=backend_api)


def swarm_ready(gemini: MagicMock, *replies: str) -> None:
    """The rules are settled first time, then these are the one-shot answers.

    The order is the order the run asks for them in: the engine, the first
    player move, the findings, and the review.
    """

    says(gemini, RULES)
    generates(
        gemini,
        f"```python\n{ENGINE_SOURCE}```",
        *replies,
    )


def test_the_whole_run_goes_through_the_real_backend(gemini, state):
    swarm_ready(
        gemini,
        json.dumps({"move": {"action": "pass"}, "explanation": "Nothing beats a pass."}),
        json.dumps(FINDINGS),
        REVIEW,
    )

    run(state, PROMPT)

    # The feed is the one "ui instructions.md" describes, produced by the swarm.
    assert [
        component
        for component in state.components()
        if component.startswith("Status")
    ] == [
        ui.COMPONENT_STATUS_INTERPRETING,
        ui.COMPONENT_STATUS_CODING,
        ui.COMPONENT_STATUS_DEPLOYING,
        ui.COMPONENT_STATUS_PLAYING,
        ui.COMPONENT_STATUS_COLLECTING,
    ]
    assert state.results(ui.COMPONENT_STATUS_INTERPRETING) == ["success"]
    # The code the swarm generated, and the game its agents played, are both
    # there to be shown.
    assert state.code == ENGINE_SOURCE
    assert state.sample[0]["move"] == {"action": "pass"}
    assert state.response == REVIEW
    assert state.title.first(ui.COMPONENT_MULTIWORD).props["pinned"] == "Skirmish"
    assert state.entry(state.awaiting).props["role"] == "next"


def test_the_swarm_drives_the_same_feed_as_the_dummy(gemini, state):
    """The seam the switch sits on, from the front end's side.

    Same prompt, same feed, either side of the switch.  This is the whole of
    what "the front end talks to a bunch of exposed python functions" has to
    mean for the two implementations to be interchangeable.
    """

    swarm_ready(
        gemini,
        json.dumps({"move": {"action": "pass"}, "explanation": "Nothing beats a pass."}),
        json.dumps(FINDINGS),
        REVIEW,
    )
    run(state, PROMPT)

    stand_in = ui.initial_state("other")
    pipeline.run_events(stand_in, PROMPT, api=dummy_api)

    assert state.components() == stand_in.components()


def test_a_question_from_the_swarm_loops_back_into_interpreting(gemini, state):
    says(
        gemini,
        "How many players are there, and what is a legal turn?",
        RULES,
    )
    generates(
        gemini,
        f"```python\n{ENGINE_SOURCE}```",
        json.dumps({"move": {"action": "pass"}, "explanation": "Nothing beats a pass."}),
        json.dumps(FINDINGS),
        REVIEW,
    )

    run(state, "something fun, you decide everything")

    # Interpreting failed because it needed clarification, and the question is
    # waiting for an answer in the feed.
    assert state.results(ui.COMPONENT_STATUS_INTERPRETING) == ["failure"]
    question = state.entries[-1]
    assert question.component == ui.COMPONENT_STATUS_QUESTION
    assert "How many players" in question.props["text"]
    assert state.entry(state.awaiting).props["role"] == "question"
    assert state.code is None

    run(state, "Two players, and a turn is passing.")

    # The answer went into the same conversation, so the run carries on.
    assert state.results(ui.COMPONENT_STATUS_INTERPRETING) == ["failure", "success"]
    assert state.status_result(ui.STATUS_COLLECTING) == "success"
    assert state.response == REVIEW


