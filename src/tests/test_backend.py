@pytest.fixture(autouse=True)
def no_live_gemini(monkeypatch) -> None:
    """Belt and braces: no test in this file may reach a real Gemini.

    The ``gemini`` fixture below covers every path through the swarm, because
    ``get_client`` is the only one there is.  This is the backstop for the rest:
    if some future test forgets the fixture, building an actual client - and
    with it spending actual money - fails the run instead of quietly happening.
    """

    monkeypatch.setattr(
        swarm.genai,
        "Client",
        MagicMock(side_effect=AssertionError("a test tried to build a real client")),
    )


@pytest.fixture
def gemini(monkeypatch) -> MagicMock:
    """The Gemini client, made of mocks.

    ``swarm.get_client`` is the only way the swarm reaches a model, so
    replacing it is enough to keep every test here off the network and out of
    the wallet.
    """

    double = MagicMock()
    monkeypatch.setattr(swarm, "get_client", lambda: double)
    return double


def _reply(value: Any) -> MagicMock:
    """A model reply: text back, or an exception standing in for a dead swarm."""

    if isinstance(value, BaseException) or (
        inspect.isclass(value) and issubclass(value, BaseException)
    ):
        return MagicMock(side_effect=value)
    return MagicMock(text=value)


def says(gemini: MagicMock, *replies: Any) -> MagicMock:
    """The Rules agent's chat, saying these things in this order."""

    chat = MagicMock()
    chat.send_message.side_effect = [_reply(reply) for reply in replies]
    gemini.chats.create.return_value = chat
    return chat


def generates(gemini: MagicMock, *replies: Any) -> None:
    """One-shot completions, in this order."""

    gemini.models.generate_content.side_effect = [_reply(reply) for reply in replies]


@pytest.fixture(autouse=True)
def clean_backend():
    """Conversations do not outlive a test."""

    backend_api.reset()
    yield
    backend_api.reset()


