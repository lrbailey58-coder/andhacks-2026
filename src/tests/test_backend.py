#: The engine the coding step is stubbed with: a whole game that ends on the
#: first move, so a run reaches the review without a long playtest.
ENGINE_SOURCE = '''"""A one-move game, generated by the Rules agent in the test suite."""


def initial_game_state(player_count):
    return {"turn": 0, "moves": 0, "players": player_count}


def list_valid_moves(game_state, player_id):
    return [{"action": "pass"}]


def execution_function(game_state, move, player_id):
    return {
        "turn": game_state["turn"] + 1,
        "moves": game_state["moves"] + 1,
        "players": game_state["players"],
    }


def eval_function(game_state):
    return 0 if game_state["moves"] >= 1 else None


def translation_function(x1, x2, p):
    return x1


def get_random_valid_move(game_state, player_id):
    return {"action": "pass"}
'''

