"""The real backend, and the switch that decides whether it is even loaded.

The front end suite runs against ``web/dummy_api.py``; these are the tests for
``backend/``, the swarm that answers when the switch is off.  Nothing here
sends a prompt: the Gemini client is a :class:`~unittest.mock.MagicMock`, so
the agents run their real logic and every model call is a stub that returns
canned text.  That is affordable where a real playtest is not, and it is the
only way to exercise the whole run - the rules conversation, codegen, the game
loop, the analyses and the review - in a second.

The last section is the connection itself: the front end's own flow, driven
through :func:`web.pipeline.turn` against the real backend, so the seam the
switch sits on is asserted rather than assumed.
"""

