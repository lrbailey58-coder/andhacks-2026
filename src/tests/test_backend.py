def test_the_switch_is_off_for_a_normal_run(monkeypatch):
    # This suite turns the switch on for itself; what is being asserted here is
    # the default it was shipped with, read before any fixture touched it.
    assert SWITCH_DEFAULT is False
    monkeypatch.setattr(app, "USE_DUMMY_API", SWITCH_DEFAULT)
