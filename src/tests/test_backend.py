def test_the_rules_agent_is_given_the_design_and_its_system_instruction(gemini):
    chat = says(gemini, RULES)
    reading = backend_api.interpret_rules("a game about deep space", (), "run-1")

    chat.send_message.assert_called_once()
    sent = chat.send_message.call_args.args[0]
    assert "deep space" in sent
